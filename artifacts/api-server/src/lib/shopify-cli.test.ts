import {test} from "node:test";
import assert from "node:assert/strict";
import {cliSecretKey,cliCredential,cliEnvironment,sameThemeFile,safeCliMessage,parseCliTheme,assertLiveConfirmation,activateCliTheme} from "./shopify-cli";
import type {Publication} from "./domain";

test("Theme Access credentials and subprocess environment are strictly store scoped",()=>{
  const a="store-a.myshopify.com",b="store-b.myshopify.com";
  assert.equal(cliSecretKey(a),"SHOPIFY_CLI_THEME_TOKEN_STORE_A");
  assert.equal(cliCredential(a,{SHOPIFY_CLI_THEME_TOKEN_STORE_A:"fixture-A",SHOPIFY_CLI_THEME_TOKEN_STORE_B:"fixture-B"}),"fixture-A");
  assert.throws(()=>cliCredential(b,{SHOPIFY_CLI_THEME_TOKEN_STORE_A:"fixture-A"}),/STORE_B/);
  assert.throws(()=>cliCredential(b,{SHOPIFY_CLI_THEME_TOKEN:"fixture-generic",SHOPIFY_FLAG_STORE:a}),/STORE_B/);
  assert.equal(cliCredential(a,{SHOPIFY_CLI_THEME_TOKEN:"fixture-generic",SHOPIFY_FLAG_STORE:a}),"fixture-generic");
  const env=cliEnvironment(a,"fixture-A","/tmp/fixture",{PATH:"/bin",DATABASE_URL:"private-db",SHOPIFY_CLI_THEME_TOKEN_STORE_B:"fixture-B",SHOPIFY_FLAG_PUBLISH:"1",SHOPIFY_FLAG_VERBOSE:"1"});
  assert.equal(env.SHOPIFY_CLI_THEME_TOKEN,"fixture-A");assert.equal(env.SHOPIFY_FLAG_STORE,a);
  for(const key of ["DATABASE_URL","SHOPIFY_CLI_THEME_TOKEN_STORE_B","SHOPIFY_FLAG_PUBLISH","SHOPIFY_FLAG_VERBOSE","SHOPIFY_FLAG_ALLOW_LIVE","SHOPIFY_FLAG_THEME_ID"])assert.ok(!(key in env));
  assert.ok(!safeCliMessage("Error fixture-A","fixture-A").includes("fixture-A"));
});
test("CLI 5 camelCase upload URLs are captured and mismatched stores are rejected",()=>{
  const shop="store-a.myshopify.com";
  const raw={id:"123",name:"New",role:"unpublished",storeDomain:shop,previewUrl:`https://${shop}?preview_theme_id=123`,editorUrl:`https://${shop}/admin/themes/123/editor`};
  assert.equal(parseCliTheme(raw,shop).id,"123");
  assert.throws(()=>parseCliTheme({...raw,role:"live"},shop),/unpublished/);
  assert.throws(()=>parseCliTheme({...raw,storeDomain:"store-b.myshopify.com"},shop),/different store/);
  assert.throws(()=>parseCliTheme({...raw,previewUrl:"https://unrelated.example"},shop),/unexpected/);
});
test("Shopify readback tolerates generated JSON headers and empty blocks, not lost content",()=>{
  const expected='{"sections":{"hero":{"settings":{"heading":"Real copy"},"blocks":{},"block_order":[]}},"order":["hero"]}';
  const actual='/* Shopify autogenerated header */\\n{"order":["hero"],"sections":{"hero":{"settings":{"heading":"Real copy"}}}}'.replace("\\n","\n");
  assert.ok(sameThemeFile("templates/product.json",expected,actual));
  assert.ok(!sameThemeFile("templates/product.json",expected,actual.replace("Real copy","Wrong copy")));
  assert.ok(sameThemeFile("assets/file.css","body{}\n","body{}\r\n"));
  assert.ok(!sameThemeFile("assets/file.css","body{color:red}","body{color:blue}"));
});
test("making a theme live always requires exact store/theme confirmation and a verified upload",()=>{
  const shop="store-a.myshopify.com",p={id:"fixture",designId:"design",title:"Test",createdAt:"2026-01-01",shop,themeId:"123",method:"theme-access-cli",status:"published",verified:true} as Publication;
  const input={expectedShop:shop,themeId:"123",confirmReplaceLiveTheme:true};
  assert.doesNotThrow(()=>assertLiveConfirmation(input,p,shop));
  assert.throws(()=>assertLiveConfirmation({...input,confirmReplaceLiveTheme:false},p,shop),/confirmation/);
  assert.throws(()=>assertLiveConfirmation({...input,themeId:"999"},p,shop),/confirmation/);
  assert.throws(()=>assertLiveConfirmation({...input,expectedShop:"store-b.myshopify.com"},p,shop),/confirmation/);
  assert.throws(()=>assertLiveConfirmation(input,{...p,verified:false},shop),/verified/);
});
test("server-side live publishing stays off even when a caller submits confirmation",async()=>{
  const original=process.env.SHOPIFY_CLI_ALLOW_LIVE_PUBLISH;
  process.env.SHOPIFY_CLI_ALLOW_LIVE_PUBLISH="false";
  try{await assert.rejects(activateCliTheme("fixture",{expectedShop:"fixture.myshopify.com",themeId:"123",expectedLiveThemeId:"456",confirmReplaceLiveTheme:true}),/disabled server-side/);}
  finally{if(original===undefined)delete process.env.SHOPIFY_CLI_ALLOW_LIVE_PUBLISH;else process.env.SHOPIFY_CLI_ALLOW_LIVE_PUBLISH=original;}
});
